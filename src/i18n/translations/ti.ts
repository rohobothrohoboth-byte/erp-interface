// Helper function to translate a menu from database key
export const translateMenu = (menuKey: string, label: string, t: any): string => {
    const translationKey = MENU_TRANSLATION_KEYS[menuKey];
    if (translationKey && t[translationKey]) {
        return t[translationKey];
    }
    return label;
};